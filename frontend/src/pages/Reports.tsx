import { useState } from 'react';
import { Download, FileText } from 'lucide-react';
import { reportApi, saveBlob, type Report, type ReportFilters, type ReportType } from '../api/workspace';
import { apiError } from '../api/work';
import { useTenant } from '../contexts/TenantContext';
import { useToast } from '../contexts/ToastContext';
import { useLoad } from '../hooks/useLoad';
import { useWorkspaceData } from '../hooks/useWorkspaceData';
import { PageHeader } from '../components/ui/PageHeader';
import { Select } from '../components/ui/Select';
import { Button } from '../components/ui/Button';
import { ErrorState } from '../components/ui/ErrorState';
import { TableSkeleton } from '../components/ui/Skeleton';
import { addDays, toDateKey } from '../components/tasks/taskMeta';

const REPORTS: { type: ReportType; label: string; filters: ('project' | 'assignee' | 'dates')[] }[] = [
  { type: 'project-status', label: 'Project status', filters: ['project', 'assignee'] },
  { type: 'overdue-tasks', label: 'Overdue tasks', filters: ['project', 'assignee'] },
  { type: 'workload', label: 'Workload', filters: ['assignee'] },
  { type: 'task-completion', label: 'Task completion', filters: ['project', 'assignee', 'dates'] },
  { type: 'milestones', label: 'Milestones', filters: ['project'] },
];

/** Live workspace reports with filters; CSV is generated by the server from the same filters. */
const Reports = () => {
  const { currentTenant } = useTenant();
  const toast = useToast();
  const tenantId = currentTenant?.id ?? '';
  const { members, projects } = useWorkspaceData(tenantId);
  const [type, setType] = useState<ReportType>('project-status');
  const [projectId, setProjectId] = useState('');
  const [assigneeId, setAssigneeId] = useState('');
  const [from, setFrom] = useState(() => toDateKey(addDays(new Date(), -29)));
  const [to, setTo] = useState(() => toDateKey(new Date()));
  const [exporting, setExporting] = useState(false);

  const def = REPORTS.find((r) => r.type === type)!;
  const filters: ReportFilters = {
    projectId: def.filters.includes('project') ? projectId : undefined,
    assigneeId: def.filters.includes('assignee') ? assigneeId : undefined,
    from: def.filters.includes('dates') ? from : undefined,
    to: def.filters.includes('dates') ? to : undefined,
  };
  const key = JSON.stringify(filters);
  const { data, error, loading } = useLoad<Report>((s) => reportApi.get(tenantId, type, filters, s), [tenantId, type, key], 'Could not build the report.');

  const exportCsv = async () => {
    setExporting(true);
    try {
      const { blob, filename } = await reportApi.csv(tenantId, type, filters);
      saveBlob(blob, filename);
    } catch (err) {
      toast.error(apiError(err, 'Could not export the report').message);
    } finally {
      setExporting(false);
    }
  };

  if (!currentTenant) return null;

  return (
    <div>
      <PageHeader
        title="Reports"
        subtitle="Built from live data each time you open them. Exports use exactly the filters shown."
        actions={
          <Button onClick={exportCsv} isLoading={exporting} disabled={!data || data.rows.length === 0}>
            <Download size={15} /> Export CSV
          </Button>
        }
      />

      <div className="report-tabs" role="tablist" aria-label="Report">
        {REPORTS.map((r) => (
          <button key={r.type} type="button" role="tab" aria-selected={type === r.type} className={type === r.type ? 'active' : ''} onClick={() => setType(r.type)}>
            <FileText size={14} aria-hidden="true" /> {r.label}
          </button>
        ))}
      </div>

      <div className="toolbar" aria-label="Report filters">
        {def.filters.includes('project') && (
          <Select aria-label="Project" value={projectId} onChange={(e) => setProjectId(e.target.value)}
            options={[{ value: '', label: 'All projects' }, ...projects.map((p) => ({ value: p.id, label: p.name }))]} />
        )}
        {def.filters.includes('assignee') && (
          <Select aria-label={type === 'project-status' ? 'Project owner' : 'Assignee'} value={assigneeId} onChange={(e) => setAssigneeId(e.target.value)}
            options={[{ value: '', label: type === 'project-status' ? 'Any owner' : 'Everyone' }, ...members.map((m) => ({ value: m.userId, label: m.name }))]} />
        )}
        {def.filters.includes('dates') && (
          <>
            <label className="date-filter">From <input type="date" value={from} max={to} onChange={(e) => setFrom(e.target.value)} /></label>
            <label className="date-filter">To <input type="date" value={to} min={from} onChange={(e) => setTo(e.target.value)} /></label>
          </>
        )}
      </div>

      <ErrorState message={error} />
      {!data ? (
        !error && <TableSkeleton rows={5} cols={6} />
      ) : (
        <section className="panel" aria-labelledby="report-title" aria-busy={loading}>
          <div className="panel-head">
            <div>
              <h2 id="report-title" className="section-heading">{data.title}</h2>
              <p className="text-xs text-muted">{data.description} Generated {new Date(data.generatedAt).toLocaleString()}.</p>
            </div>
            <span className="count-pill">{data.rows.length} row{data.rows.length === 1 ? '' : 's'}</span>
          </div>
          {data.rows.length === 0 ? (
            <p className="dash-empty">No data for these filters.</p>
          ) : (
            <div className="table-container">
              <table className="table report-table">
                <caption className="sr-only">{data.title}</caption>
                <thead>
                  <tr>{data.columns.map((c) => <th key={c.key} scope="col" className={c.numeric ? 'num' : ''}>{c.label}</th>)}</tr>
                </thead>
                <tbody>
                  {data.rows.map((row, i) => (
                    <tr key={i}>{row.map((cell, j) => <td key={j} className={data.columns[j].numeric ? 'num' : ''}>{cell || <span className="text-muted">—</span>}</td>)}</tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </section>
      )}
    </div>
  );
};

export default Reports;
