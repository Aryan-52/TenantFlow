package io.github.aryan52.tenantflow.storage;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.regex.Pattern;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Durable local storage ({@code tenantflow.storage.type=filesystem}): one file per object
 * under a configured root directory. The default for local development, so uploads work
 * without any extra service and survive restarts.
 *
 * <p>Keys are generated by the application, but are still validated and resolved strictly
 * inside the root so no key can escape it. Writes go to a temporary file in the same
 * directory and are then moved into place, so a crashed upload never leaves a partial
 * object behind under the real key.
 */
public class FilesystemObjectStorage implements ObjectStorage {

	private static final Logger log = LoggerFactory.getLogger(FilesystemObjectStorage.class);
	/** Segments of letters, digits, '-' and '_' separated by '/'; no dots, so no "..". */
	private static final Pattern SAFE_KEY = Pattern.compile("[A-Za-z0-9_-]+(/[A-Za-z0-9_-]+)*");

	private final Path root;

	/**
	 * Never fails: an unusable directory is logged here and reported per request as storage
	 * unavailable (503), like an unreachable bucket, instead of breaking unrelated requests.
	 */
	public FilesystemObjectStorage(Path root) {
		this.root = root.toAbsolutePath().normalize();
		try {
			ensureRoot();
			log.info("File storage: local directory {}", this.root);
		} catch (StorageUnavailableException e) {
			log.error("File storage directory {} is not usable; uploads and downloads will fail until it is fixed "
					+ "(set TENANTFLOW_STORAGE_DIR)", this.root, e.getCause());
		}
	}

	private void ensureRoot() {
		try {
			Files.createDirectories(root);
		} catch (IOException e) {
			throw new StorageUnavailableException("Cannot create the storage directory", e);
		}
		if (!Files.isWritable(root)) {
			throw new StorageUnavailableException("The storage directory is not writable", null);
		}
	}

	Path resolve(String key) {
		if (key == null || !SAFE_KEY.matcher(key).matches()) {
			throw new IllegalArgumentException("Invalid storage key");
		}
		Path path = root.resolve(key).normalize();
		if (!path.startsWith(root)) {
			throw new IllegalArgumentException("Invalid storage key");
		}
		return path;
	}

	@Override
	public void put(String key, InputStream content, long length, String contentType) {
		Path target = resolve(key);
		ensureRoot();
		Path temp = null;
		try {
			Files.createDirectories(target.getParent());
			temp = Files.createTempFile(target.getParent(), ".upload-", ".part");
			Files.copy(content, temp, StandardCopyOption.REPLACE_EXISTING);
			try {
				Files.move(temp, target, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
			} catch (AtomicMoveNotSupportedException e) {
				Files.move(temp, target, StandardCopyOption.REPLACE_EXISTING);
			}
			temp = null;
		} catch (IOException e) {
			throw new StorageUnavailableException("Could not store the file", e);
		} finally {
			if (temp != null) {
				try {
					Files.deleteIfExists(temp);
				} catch (IOException ignored) {
					// Best effort; a stray .part file is never served.
				}
			}
		}
	}

	@Override
	public InputStream get(String key) {
		Path path = resolve(key);
		try {
			return Files.newInputStream(path);
		} catch (NoSuchFileException e) {
			// A missing root is an outage (wrong or unmounted directory), not a lost object.
			if (!Files.isDirectory(root)) {
				throw new StorageUnavailableException("The storage directory is missing", e);
			}
			throw new StoredObjectMissingException(key, e);
		} catch (IOException e) {
			throw new StorageUnavailableException("Could not read the file", e);
		}
	}

	@Override
	public void delete(String key) {
		try {
			Files.deleteIfExists(resolve(key));
		} catch (IOException e) {
			throw new StorageUnavailableException("Could not delete the file", e);
		}
	}
}
